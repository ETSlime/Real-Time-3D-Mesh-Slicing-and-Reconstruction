//*****************************************************************************
// グローバル変数
//*****************************************************************************
char		g_aStrDebug[1024] = {"\0"};	// デバッグ情報


//=============================================================================
// デバッグ表示処理の描画処理
//=============================================================================
void DrawDebugProc(void)
{
	RECT rect = {0, 0, SCREEN_WIDTH, SCREEN_HEIGHT};

	DebugTextOut(g_aStrDebug, 0, 0);

	// 情報クリア
	memset(g_aStrDebug, 0, sizeof g_aStrDebug);
}

//=============================================================================
// デバッグ表示の登録
//=============================================================================
void PrintDebugProc(const char* fmt, ...)
{
    if (fmt == nullptr)
    {
        return;
    }

    // 1回の呼び出しで生成する文字列を保持する。
    char buffer[1024] = {};

    va_list arguments;
    va_start(arguments, fmt);

    // 標準の書式処理を使用する。
    // 容量を超える場合は切り詰め、終端文字を保証する。
    vsnprintf_s(
        buffer,
        sizeof(buffer),
        _TRUNCATE,
        fmt,
        arguments);

    va_end(arguments);

    // 文字列全体を追加できる場合だけ、描画用バッファへ連結する。
    const std::size_t currentLength = std::strlen(g_aStrDebug);
    const std::size_t messageLength = std::strlen(buffer);

    if (currentLength < sizeof(g_aStrDebug)
        && messageLength < sizeof(g_aStrDebug) - currentLength)
    {
        strcat_s(
            g_aStrDebug,
            sizeof(g_aStrDebug),
            buffer);
    }
}

